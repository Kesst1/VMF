import { notFound } from "next/navigation";
import { sql } from "@/lib/db";
import { PageHeading, EmptyState } from "@/components/SiteShell";

export const dynamic = "force-dynamic";

type StandingRow = {
  id: string;
  name: string;
  group_name: string | null;
  played: number;
  won: number;
  drawn: number;
  lost: number;
  gf: number;
  ga: number;
  points: number;
  goal_difference: number;
};

function compareTeams(a: StandingRow, b: StandingRow) {
  return b.points - a.points ||
    b.goal_difference - a.goal_difference ||
    b.gf - a.gf ||
    a.name.localeCompare(b.name);
}

function Table({ teams, qualification }: { teams: StandingRow[]; qualification: "top-three" | "last-out" | "none" }) {
  const sorted = [...teams].sort(compareTeams);
  return (
    <div className="table-wrap">
      <table className="data-table">
        <thead>
          <tr>
            <th>#</th><th>Team</th><th>P</th><th>W</th><th>D</th><th>L</th>
            <th>GF</th><th>GA</th><th>GD</th><th>Pts</th>
            {qualification !== "none" && <th>Qualification</th>}
          </tr>
        </thead>
        <tbody>
          {sorted.map((team, index) => {
            const qualified = qualification === "top-three"
              ? index < 3
              : qualification === "last-out"
                ? index < sorted.length - 1
                : false;
            return (
              <tr key={team.id}>
                <td>{index + 1}</td>
                <td><b>{team.name}</b></td>
                <td>{team.played}</td><td>{team.won}</td><td>{team.drawn}</td><td>{team.lost}</td>
                <td>{team.gf}</td><td>{team.ga}</td><td>{team.goal_difference > 0 ? `+${team.goal_difference}` : team.goal_difference}</td>
                <td><b>{team.points}</b></td>
                {qualification !== "none" && (
                  <td>
                    <span className="pill" style={{ color: qualified ? "#15803d" : "#b91c1c" }}>
                      {qualified ? "QUALIFIED" : "ELIMINATED"}
                    </span>
                  </td>
                )}
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}

export default async function TablePage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  let competition: any;
  let rows: StandingRow[] = [];

  try {
    const competitions = await sql`
      SELECT id, name, format FROM competitions WHERE id = ${id} LIMIT 1
    `;
    competition = competitions[0];

    if (competition) {
      if (String(competition.format) === "table_elimination") {
        // Backfill group assignments for competitions generated by older code.
        await sql`
          WITH unassigned AS (
            SELECT ct.team_id,
                   ROW_NUMBER() OVER (ORDER BY t.name ASC, ct.team_id ASC) AS rn
            FROM competition_teams ct
            JOIN teams t ON t.id = ct.team_id
            WHERE ct.competition_id = ${id}
              AND ct.group_name IS NULL
          )
          UPDATE competition_teams ct
          SET group_name = CASE
            WHEN unassigned.rn <= 4 THEN 'A'
            WHEN unassigned.rn <= 8 THEN 'B'
            WHEN unassigned.rn <= 12 THEN 'C'
            ELSE 'D'
          END
          FROM unassigned
          WHERE ct.competition_id = ${id}
            AND ct.team_id = unassigned.team_id
        `;
      }
      const groupedFormat = ["table_elimination", "champions"].includes(String(competition.format));
      const result = await sql`
        SELECT
          ct.group_name, t.id, t.name,
          COUNT(f.id)::int AS played,
          COUNT(f.id) FILTER (
            WHERE (f.home_team_id = t.id AND f.home_score > f.away_score)
               OR (f.away_team_id = t.id AND f.away_score > f.home_score)
          )::int AS won,
          COUNT(f.id) FILTER (WHERE f.home_score = f.away_score)::int AS drawn,
          COUNT(f.id) FILTER (
            WHERE (f.home_team_id = t.id AND f.home_score < f.away_score)
               OR (f.away_team_id = t.id AND f.away_score < f.home_score)
          )::int AS lost,
          COALESCE(SUM(CASE WHEN f.home_team_id = t.id THEN f.home_score ELSE f.away_score END), 0)::int AS gf,
          COALESCE(SUM(CASE WHEN f.home_team_id = t.id THEN f.away_score ELSE f.home_score END), 0)::int AS ga
        FROM competition_teams ct
        JOIN teams t ON t.id = ct.team_id
        LEFT JOIN fixtures f
          ON f.competition_id = ct.competition_id
         AND f.status = 'confirmed'
         AND (f.home_team_id = t.id OR f.away_team_id = t.id)
         AND (${groupedFormat} = FALSE OR f.stage = 'group')
        WHERE ct.competition_id = ${id}
        GROUP BY ct.group_name, t.id, t.name
      `;
      rows = result.map((row: any) => ({
        ...row,
        played: Number(row.played || 0), won: Number(row.won || 0),
        drawn: Number(row.drawn || 0), lost: Number(row.lost || 0),
        gf: Number(row.gf || 0), ga: Number(row.ga || 0),
        points: Number(row.won || 0) * 3 + Number(row.drawn || 0),
        goal_difference: Number(row.gf || 0) - Number(row.ga || 0)
      }));
    }
  } catch (error) {
    console.error("Standings page error:", error);
  }

  if (!competition) notFound();

  const format = String(competition.format);
  const isTableElimination = format === "table_elimination";
  const isChampions = format === "champions";
  const groups: Record<string, StandingRow[]> = {};
  for (const team of rows) {
    const groupName = team.group_name || "League";
    (groups[groupName] ||= []).push(team);
  }
  const groupNames = Object.keys(groups).sort();
  const qualifiedCount = isTableElimination ? groupNames.length * 3 : 0;

  return (
    <main className="container">
      <PageHeading
        eyebrow="COMPETITION TABLE"
        title={competition.name}
        description={isTableElimination
          ? "Four groups of four. The top three teams in each group qualify for the 12-team elimination bracket."
          : isChampions
            ? "Group standings and overall qualification ranking."
            : "League standings calculated from confirmed results."}
      />

      {isTableElimination && (
        <section className="content-section">
          <div className="stat-grid">
            <div className="stat-card"><strong>4</strong><span>Groups</span></div>
            <div className="stat-card"><strong>16</strong><span>Teams</span></div>
            <div className="stat-card"><strong>{qualifiedCount}</strong><span>Qualified</span></div>
            <div className="stat-card"><strong>4</strong><span>Eliminated</span></div>
          </div>
          <p className="notice" style={{ marginTop: 18 }}>
            The top three teams in Groups A, B, C and D advance. The fourth-placed team in each group is eliminated.
          </p>
        </section>
      )}

      <section className="content-section">
        {rows.length === 0 ? (
          <EmptyState title="Standings not available" detail="Add teams, generate fixtures and confirm match results to populate this table." />
        ) : isTableElimination || isChampions ? (
          <div style={{ display: "grid", gap: 34 }}>
            {groupNames.map(groupName => (
              <section key={groupName}>
                <div className="section-head"><div><p className="eyebrow">GROUP STAGE</p><h2>Group {groupName}</h2></div></div>
                <Table teams={groups[groupName]} qualification={isTableElimination ? "top-three" : "last-out"} />
              </section>
            ))}
          </div>
        ) : (
          <Table teams={rows} qualification="none" />
        )}
      </section>
    </main>
  );
}
